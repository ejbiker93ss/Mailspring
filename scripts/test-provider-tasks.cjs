const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const source = fs.readFileSync('app/internal_packages/mail-kanban/lib/provider-task-data.ts', 'utf8');
const taskExports = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: taskExports });
const { taskChanges, taskSources } = taskExports;
const base = { id: 'task', title: 'Existing', notes: 'Notes', due: '2026-09-25', status: '2', priority: '5', raw: { percentComplete: 30 } };
const plain = v => JSON.parse(JSON.stringify(v));
assert.deepEqual(plain(taskChanges(base, base, true)), {});
assert.deepEqual(plain(taskChanges({ ...base, title: 'Renamed' }, base, true)), { subject: 'Renamed' });
assert.deepEqual(plain(taskChanges({ ...base, status: '1' }, base, true)), { status: 1, percentComplete: 100 });
assert.deepEqual(plain(taskChanges({ ...base, due: '' }, base, true)), { due: null, start: null, useDateTime: false });
assert.deepEqual(plain(taskChanges({ ...base, notes: '<script>&\ntext' }, base, true)), { description: '&lt;script&gt;&amp;<br>text' });
assert.deepEqual(plain(taskChanges({ ...base, status: 'completed' }, base, false)), { status: 'completed' });
assert.deepEqual(plain(taskChanges({ ...base, due: '' }, base, false)), { dueDateTime: null });
assert.equal(taskSources([{id:'a',owner:'one',name:'Shared',isSharedItem:true}], true)[0].readOnly, true);
assert.equal(taskSources({value:[{id:'a',displayName:'Mine',isOwner:true}]}, false)[0].readOnly, false);
assert.throws(() => taskSources({}, true));
console.log('PASS: task updates only send edited fields, preserve metadata, escape notes, map completion and dates, enforce read-only lists, reject invalid responses');
